def role_skills(pdata: dict) -> dict:
    return {r.get("role"): list(r.get("skills") or []) for r in pdata.get("roster") or []
            if isinstance(r, dict) and r.get("role")}


def check_adaptation(pid: str, pdata: dict, home, rep: Report, where: str) -> None:
    """A custom play keeps the craft of the bundled play it was adapted from."""
    roles = role_skills(pdata)
    base_ref = pdata.get("based_on")
    base = None
    if isinstance(base_ref, str) and PLAY_REF.match(base_ref):
        base_info = discover_plays(home, Report()).get(PLAY_REF.match(base_ref).group(1))
        if base_info is not None:
            base = load_yaml(base_info["dir"] / "play.yaml", Report(), base_ref)
    if not isinstance(base, dict):
        if not any(roles.values()):
            rep.warn(where, "no role has shared skills; give writing, research and review roles the bundled skills for their craft")
        return
    base_roles = role_skills(base)
    base_all = sorted({skill for skills in base_roles.values() for skill in skills})
    if base_all and not any(roles.values()):
        rep.err(where, f"adapted from {base_ref} but dropped every role skill ({', '.join(base_all)}); keep the skills of the roles you kept")
        return
    for role, skills in base_roles.items():
        if role in roles and skills and not roles[role]:
            rep.err(where, f"role '{role}' dropped its skills from {base_ref} ({', '.join(skills)})")


