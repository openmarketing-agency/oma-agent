def cmd_new(args) -> int:
    home = resolve_home(args.home, required=True)
    new_id = args.play_id
    if not SLUG.match(new_id):
        fail("The play id must be a lowercase, hyphen-separated slug, such as 'marketplace-launch'.", 2)
    rep = Report()
    plays = discover_plays(home, rep)
    if new_id in plays:
        fail(f"A play named '{new_id}' already exists ({plays[new_id]['source']}). Pick a new id.")
    target = custom_root(home) / new_id
    if target.exists():
        fail(f"{target} already exists. Nothing was changed.")
    if args.source:
        info = plays.get(args.source)
        if info is None:
            fail(f"Play '{args.source}' not found. Run 'plays.py list'.")
        src_data = load_yaml(info["dir"] / "play.yaml", rep, f"{info['rel']}/play.yaml")
        if not isinstance(src_data, dict):
            return rep.emit(args.json)
        text = (info["dir"] / "play.yaml").read_text(encoding="utf-8")
        text = re.sub(r"(?m)^based_on:.*\n", "", text)
        text, n_id = re.subn(r"(?m)^id:.*$", f"id: {new_id}", text, count=1)
        text, n_ver = re.subn(
            r"(?m)^version:.*$", f"version: 1\nbased_on: {args.source}@{src_data.get('version')}", text, count=1
        )
        if not (n_id and n_ver):
            fail("The source play has no top-level id or version line to rewrite.")
        target.mkdir(parents=True)
        (target / "play.yaml").write_text(text, encoding="utf-8")
        for item in info["dir"].iterdir():
            if item.name == "play.yaml" or item.is_symlink() or not item.is_file():
                continue
            (target / item.name).write_bytes(item.read_bytes())
    else:
        target.mkdir(parents=True)
        (target / "play.yaml").write_text(SKELETON_PLAY.replace("__PLAY_ID__", new_id), encoding="utf-8")
        (target / "rules.md").write_text(SKELETON_RULES, encoding="utf-8")
        (target / "example.md").write_text(SKELETON_EXAMPLE, encoding="utf-8")
    out = {"created": str(target), "play_yaml": str(target / "play.yaml"), "rules_md": str(target / "rules.md"),
           "next": f"Edit both files for this business, then run: plays.py validate {new_id}"}
    if args.json:
        print(json.dumps(out, indent=2))
    else:
        for key, value in out.items():
            print(f"{key}: {value}")
    return 0


