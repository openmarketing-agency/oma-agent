#!/usr/bin/env python3
"""Reference plays for OMA campaigns.

Bundled plays in ../plays are read-only references shipped with this skill.
The user's own plays live in <default Hermes home>/oma/plays/<play-id>/.

  list [--json]                          List bundled and custom plays.
  show <play-id> [--json]                Print a play's source, version and file paths.
  new <play-id> --from <play-id>         Copy a play into oma/plays/ to adapt it.
  new <play-id> --blank                  Start a custom play from a skeleton.
  validate [<play-id>] [--json]          Check plays against the schema and vocabulary.
  ideas [--section S] [--play P] [--json]  List the campaign ideas catalog.
  jobs <campaign-id> --play PLAY --agent ID --sources TEXT [--timezone TZ] [--json]
                                         Draft job declarations for the campaign's agents.
  catalog [--write]                      Maintainers: compare or rewrite plays/catalog.yaml.

Every command accepts --home PATH, the default Hermes home. Without it the script asks
`hermes -p default config path`, then falls back to $HERMES_HOME.
Exit codes: 0 ok, 1 problems found or the command failed, 2 usage error.
"""
