def schedule_for(cadence: str, seed: str, local_hours: bool):
    """Native cron expression for a cadence, with a minute and hour spread by seed."""
    match = SCHEDULABLE.match(cadence or "")
    if not match:
        return None
    if match.group(1):
        count, unit = int(match.group(1)), match.group(2)
    else:
        count, unit = 1, {"hourly": "hour", "daily": "day", "weekly": "week", "monthly": "month"}[cadence]
    h = int(hashlib.sha256(seed.encode("utf-8")).hexdigest(), 16)
    minute = h % 60
    if minute in (0, 30):
        minute += 7
    if unit == "hour":
        return f"{minute} * * * *"
    h //= 60
    hour = 7 + h % 12 if local_hours else h % 24
    h //= 24
    if unit == "day":
        if count == 1:
            return f"{minute} {hour} * * *"
        hours = sorted({(hour + (i * 24) // count) % 24 for i in range(min(count, 24))})
        return f"{minute} {','.join(map(str, hours))} * * *"
    if unit == "week":
        if count == 1:
            return f"{minute} {hour} * * {1 + h % 5}"
        if count >= 7:
            return f"{minute} {hour} * * *"
        patterns = {2: ["1,4", "2,5"], 3: ["1,3,5"], 4: ["1,2,4,5"], 5: ["1-5"], 6: ["1-6"]}
        options = patterns[count]
        return f"{minute} {hour} * * {options[h % len(options)]}"
    if unit == "month":
        day = 1 + h % 28
        if count == 1:
            return f"{minute} {hour} {day} * *"
        n = min(count, 4)
        days = sorted({((day - 1 + (i * 28) // n) % 28) + 1 for i in range(n)})
        return f"{minute} {hour} {','.join(map(str, days))} * *"
    if unit == "quarter" and count == 1:
        day = 1 + h % 28
        first = 1 + (h // 28) % 3
        months = ",".join(str(first + 3 * i) for i in range(4))
        return f"{minute} {hour} {day} {months} *"
    return None


